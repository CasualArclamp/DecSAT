//! Names for CCSDS spacecraft identifiers: who the CCSDS registry says has
//! the identifier a transfer frame's header carries ([`crate::ccsds::Header`]).
//!
//! The table is the Spacecraft Identifier registry of the Space Assigned
//! Numbers Authority (SANA, <https://sanaregistry.org/r/spacecraftid/>), as
//! it stood on 2026-11-12: the assignments in force (not those returned) for
//! version 1 (TM, 132.0-B-3 §4.1.2.2) and version 2 (AOS, 732.0-B-4
//! §4.1.2.2) frames. The rules it is kept by are CCSDS 320.0-M-7.
//!
//! A name from here is a hint, not proof. An identifier is unique only
//! within a frame version and a frequency band, it is given out again once
//! a mission returns it, and plenty of commercial satellites use one they
//! never registered.

/// One assignment: the header's version field (0 TM, 1 AOS), the
/// identifier, the band's letter ("S", "X", "Ku", …; "other") and the
/// spacecraft's name as registered.
pub type Assignment = (u8, u16, &'static str, &'static str);

/// Every assignment of `scid` for frames of `version` (the header's field:
/// 0 TM, 1 AOS), in any band.
///
/// Rust note: `partition_point` is a binary search — the table is sorted by
/// (version, identifier), so the entries wanted are one run of it, and the
/// slice returned borrows that run without copying.
pub fn assigned(version: u8, scid: u16) -> &'static [Assignment] {
    let lo = TABLE.partition_point(|a| (a.0, a.1) < (version, scid));
    let hi = TABLE.partition_point(|a| (a.0, a.1) <= (version, scid));
    &TABLE[lo..hi]
}

/// The registry's band letters a downlink at `rf_mhz` could be listed
/// under, by the satellite bands as used (Ku from 10.7 GHz, not radar's
/// 12 GHz). The registry splits 18–40 GHz into "K" and "Ka"; both count.
pub fn bands(rf_mhz: f64) -> &'static [&'static str] {
    match rf_mhz {
        f if f < 30.0 => &[],
        f if f < 300.0 => &["VHF"],
        f if f < 1_000.0 => &["UHF"],
        f if f < 2_000.0 => &["L"],
        f if f < 3_400.0 => &["S"],
        f if f < 7_000.0 => &["C"],
        f if f < 10_700.0 => &["X"],
        f if f < 17_700.0 => &["Ku"],
        f if f < 40_000.0 => &["K", "Ka"],
        _ => &[],
    }
}

/// The registry's names for an identifier, for a status line: those in the
/// band `rf_mhz` (the frequency it was heard on, if known) falls in —
/// "EUTELSAT-172B (Ku band)" — and those registered without a band (older
/// entries, the registry's "Other"): "HYLAS (no band given)". With neither,
/// or no frequency, all of them by band: "none for Ku band · S: Aqua · X:
/// Aqua, Terra". `None`: the identifier is not in the registry at all.
pub fn describe(version: u8, scid: u16, rf_mhz: Option<f64>) -> Option<String> {
    let all = assigned(version, scid);
    if all.is_empty() {
        return None;
    }
    let here = rf_mhz.map(bands).unwrap_or(&[]);
    let mine: Vec<&str> = all
        .iter()
        .filter(|a| here.contains(&a.2))
        .map(|a| a.3)
        .collect();
    let unbanded: Vec<&str> = all
        .iter()
        .filter(|a| a.2 == "other" && !here.is_empty())
        .map(|a| a.3)
        .collect();
    if !mine.is_empty() || !unbanded.is_empty() {
        let mut parts = Vec::new();
        if !mine.is_empty() {
            parts.push(format!("{} ({} band)", list(&mine), here.join("/")));
        }
        if !unbanded.is_empty() {
            parts.push(format!("{} (no band given)", list(&unbanded)));
        }
        return Some(parts.join(" · "));
    }
    // By band, in the table's order (it is sorted by band within an
    // identifier, so each band's names are together).
    let mut parts: Vec<String> = Vec::new();
    let mut i = 0;
    while i < all.len() {
        let band = all[i].2;
        let n = all[i..].iter().take_while(|a| a.2 == band).count();
        let names: Vec<&str> = all[i..i + n].iter().map(|a| a.3).collect();
        parts.push(format!("{band}: {}", list(&names)));
        i += n;
    }
    let s = parts.join(" · ");
    Some(if here.is_empty() {
        s
    } else {
        format!("none for {} band · {s}", here.join("/"))
    })
}

/// Up to three names, then how many more.
fn list(names: &[&str]) -> String {
    let mut s = names[..names.len().min(3)].join(", ");
    if names.len() > 3 {
        s.push_str(&format!(" and {} more", names.len() - 3));
    }
    s
}

